#!/usr/bin/env node
// Usage: node scripts/vault/tide-env.mjs <realm> [--force]
// Reads tidecloak-setup/tidecloak.json and writes .env.local for TideCloak mode.
// Prints only the keys written, never values.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const args = process.argv.slice(2);
const force = args.includes("--force");
const realm = args.find((a) => !a.startsWith("--"));
if (!realm || !/^[A-Za-z0-9._-]+$/.test(realm)) {
  console.error("Usage: node scripts/vault/tide-env.mjs <realm> [--force]");
  process.exit(2);
}

const root = process.cwd();
const adapterPath = resolve(root, "tidecloak-setup", "tidecloak.json");
const outPath = resolve(root, ".env.local");

if (!existsSync(adapterPath)) {
  console.error("Missing tidecloak-setup/tidecloak.json. Run the realm init first.");
  process.exit(1);
}
if (existsSync(outPath) && !force) {
  console.error(".env.local already exists. Re-run with --force to overwrite.");
  process.exit(1);
}

let adapter;
try {
  adapter = JSON.parse(readFileSync(adapterPath, "utf8").replace(/^﻿/, ""));
} catch {
  console.error("tidecloak-setup/tidecloak.json is not valid JSON.");
  process.exit(1);
}
if (adapter.realm && adapter.realm !== realm) {
  console.error(`Warning: adapter realm differs from the requested realm; using the requested realm.`);
}

const authServer = "http://localhost:8080";
const clientId = typeof adapter.resource === "string" && adapter.resource ? adapter.resource : "myclient";
const adapterJson = JSON.stringify(adapter);

const env = {
  AUTH_MODE: "tidecloak",
  NEXT_PUBLIC_AUTH_MODE: "tidecloak",
  TIDECLOAK_AUTH_SERVER_URL: authServer,
  NEXT_PUBLIC_TIDECLOAK_AUTH_SERVER_URL: authServer,
  TIDECLOAK_REALM: realm,
  NEXT_PUBLIC_TIDECLOAK_REALM: realm,
  TIDECLOAK_CLIENT_ID: clientId,
  NEXT_PUBLIC_TIDECLOAK_CLIENT_ID: clientId,
  NEXT_PUBLIC_TIDECLOAK_REDIRECT_URI: "http://localhost:3000/auth/redirect",
  TIDECLOAK_ADAPTER_JSON: adapterJson,
  NEXT_PUBLIC_TIDECLOAK_ADAPTER_JSON: adapterJson,
  DATABASE_URL: "postgresql://businessvault:businessvault@localhost:5432/businessvault",
  S3_ENDPOINT: "http://localhost:9000",
  S3_PUBLIC_ENDPOINT: "http://localhost:9000",
  S3_BUCKET: "businessvault",
  S3_ACCESS_KEY_ID: "businessvault",
  S3_SECRET_ACCESS_KEY: "businessvault-secret",
  S3_REGION: "us-east-1",
};

// Single-quote values so dotenv keeps the JSON intact (no variable expansion, no comment parsing).
const quote = (v) => (/^[A-Za-z0-9_:/.@-]*$/.test(v) ? v : `'${v.replace(/'/g, "\\'")}'`);
const body = `# Generated by scripts/vault/tide-env.mjs. Do not commit.\n${Object.entries(env).map(([k, v]) => `${k}=${quote(v)}`).join("\n")}\n`;
writeFileSync(outPath, body, { encoding: "utf8", mode: 0o600 });

console.log(`Wrote .env.local with keys:\n${Object.keys(env).map((k) => `  ${k}`).join("\n")}`);
